local Logger = require("core.logger")
local Shell = require("utils.shell")
local File = require("utils.file")
local Paths = require("core.paths")

-- Auto-boot (Termux:Boot) installer/uninstaller from the menu.
--
-- install.sh already writes ~/.termux/boot/start-rejoin.sh on a fresh install, but
-- re-installing it by hand meant running the whole installer again. This module owns
-- that one file: install, uninstall, status and the boot log tail. The generated
-- script is the same shape as install.sh's (update first unless disabled, then hand
-- over to termux-boot.sh) so both stay interchangeable.
--
-- The absolute repo folder is baked in as REJOIN_DIR, so the script keeps working
-- even though Termux:Boot starts it with no terminal and no working directory.

local Boot = {}

local SCRIPT_NAME = "start-rejoin.sh"
local BOOT_APP_PKG = "com.termux.boot"

local function quote(s)
    return "'" .. tostring(s or ""):gsub("'", "'\\''") .. "'"
end

function Boot.home()
    local home = os.getenv("HOME")
    if not home or home == "" then home = "/data/data/com.termux/files/usr" end
    return home
end

function Boot.bootDir()
    return Boot.home() .. "/.termux/boot"
end

function Boot.scriptPath()
    return Boot.bootDir() .. "/" .. SCRIPT_NAME
end

-- Absolute path of the repo (the same root the engine keeps its state in).
function Boot.dir()
    return Paths.base()
end

function Boot.logPath()
    return Paths.data("boot.log")
end

-- The boot script content. `dir` is the absolute repo folder.
function Boot.script(dir)
    -- The "Generated by rejoin install.sh" marker is what the main menu watches to
    -- report the device as set up, so the menu-made script says it too.
    return string.format([[#!/data/data/com.termux/files/usr/bin/sh
# Rejoin auto-start on device boot (Termux:Boot plugin).
#
# Generated by rejoin install.sh (menu: Auto-boot -> Install). Safe to delete:
# use the menu (Auto-boot -> Uninstall) or just rm this file.
#
# Updates from GitHub first (unless %s/data/no-auto-update exists), then hands
# over to termux-boot.sh. Log: %s/data/boot.log

REJOIN_DIR=%s
export REJOIN_DIR
if [ -f "$REJOIN_DIR/update.sh" ] && [ ! -f "$REJOIN_DIR/data/no-auto-update" ]; then
    sh "$REJOIN_DIR/update.sh" --boot </dev/null >/dev/null 2>>"$REJOIN_DIR/data/boot.log"
fi
exec sh "$REJOIN_DIR/termux-boot.sh"
]], dir, dir, quote(dir))
end

-- A script from an older install (the installer's own wording) is a different file
-- but the same job, so either counts as installed.
function Boot.installed()
    return File.exists(Boot.scriptPath())
end

function Boot.install()
    local dir = Boot.dir()
    local target = dir .. "/termux-boot.sh"
    if not File.exists(target) then
        return false, "termux-boot.sh tidak ada di " .. dir
    end
    local okMk, errMk = pcall(function() os.execute("mkdir -p " .. quote(Boot.bootDir())) end)
    if not okMk then return false, "gagal buat folder boot: " .. tostring(errMk) end
    local path = Boot.scriptPath()
    local ok, err = File.write(path, Boot.script(dir))
    if not ok then return false, "gagal menulis " .. path .. " (" .. tostring(err) .. ")" end
    Shell.exec("chmod +x " .. quote(path))
    Logger.info("Boot: script boot ditulis: " .. path)
    return true, path
end

function Boot.uninstall()
    local path = Boot.scriptPath()
    if not File.exists(path) then return false, "script boot belum terpasang" end
    local ok, err = os.remove(path)
    if not ok then return false, "gagal hapus: " .. tostring(err) end
    Logger.info("Boot: script boot dihapus: " .. path)
    return true, path
end

-- Termux:Boot must come from the same source as Termux, otherwise Android ignores it.
function Boot.appInstalled()
    local _, out = Shell.exec("pm list packages " .. BOOT_APP_PKG)
    if not out then return false end
    return out:find(BOOT_APP_PKG, 1, true) ~= nil
end

function Boot.status()
    return {
        installed = Boot.installed(),
        path = Boot.scriptPath(),
        app = Boot.appInstalled(),
        log = Boot.logPath(),
        logExists = File.exists(Boot.logPath()),
    }
end

-- Last lines of data/boot.log, or nil + reason.
function Boot.tailLog(lines)
    local path = Boot.logPath()
    if not File.exists(path) then return nil, "no_log" end
    local _, out = Shell.exec("tail -n " .. tostring(math.max(1, lines or 10)) .. " " .. quote(path))
    if not out or out == "" then return nil, "no_log" end
    return out
end

return Boot
