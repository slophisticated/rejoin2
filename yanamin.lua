    os.execute("stty sane 2>/dev/null")
    os.execute("stty echo icanon opost onlcr 2>/dev/null")
    io.write("\r\27[2J\27[H")
    print(tostring(msg))
    io.flush()
    if os.getenv("REJOIN_WRAPPER") == "1" then os.exit(75) end
end

