-- Run from the repository root: lua tests/boot_test.lua
-- Auto-boot script content/install/uninstall, and what the uninstall menu promises to
-- remove (and NOT remove: the repo, other Autoexecute scripts).
local passed, failed = 0, 0
local function test(name, fn)
    local ok, err = xpcall(fn, debug.traceback)
    if ok then
        passed = passed + 1
        print("PASS: " .. name)
    else
        failed = failed + 1
        print("FAIL: " .. name .. "\n" .. tostring(err))
    end
end

local files, execs = {}, {}
local function stub(name, value) package.loaded[name] = value end
local noop = function() end

stub("core.logger", { info = noop, warn = noop, error = noop, debug = noop })
stub("core.paths", {
    base = function() return "/repo" end,
    data = function(n) return "/repo/data/" .. tostring(n) end,
    dataDir = function() return "/repo/data" end,
    config = function() return "/repo/config/config.lua" end,
    resolve = function(p) return p end,
    ensure = function() return "/repo" end,
    announce = noop,
})
stub("utils.file", {
    exists = function(p)
        if files[p] ~= nil then return true end
        -- Treat a folder as existing when it has any child (the engine only asks
        -- about files, but uninstall checks folders before rm -rf).
        local prefix = p .. "/"
        for key in pairs(files) do
            if key:sub(1, #prefix) == prefix then return true end
        end
        return false
    end,
    read = function(p) return files[p] end,
    write = function(p, s) files[p] = s; return true end,
})
stub("utils.shell", { exec = function(cmd) execs[#execs + 1] = cmd; return true, "line\n" end })
stub("core.config", { get = function() return { appAutoExecutePath = "/sdcard/Delta/Autoexecute" } end })

local function reset()
    files, execs = {}, {}
    files["/repo/termux-boot.sh"] = "#!/bin/sh\n"
    package.loaded["managers.boot"] = nil
    package.loaded["managers.uninstall"] = nil
end
reset()

local envHome = os.getenv("HOME")
local realGetenv = os.getenv
os.getenv = function(k) if k == "HOME" then return "/home/tester" end return envHome end
local realExecute, realRemove = os.execute, os.remove
os.execute = function(cmd)
    execs[#execs + 1] = cmd
    -- Simulate `rm -rf <path>` so the post-check sees the target gone.
    local target = tostring(cmd):match("^rm %-rf '(.+)'$")
    if target then
        files[target] = nil
        for key in pairs(files) do
            if key:sub(1, #target + 1) == target .. "/" then files[key] = nil end
        end
    end
    return true
end
os.remove = function(p) files[p] = nil; return true end

local SCRIPT = "/home/tester/.termux/boot/start-rejoin.sh"

local function fresh(module)
    package.loaded["managers." .. module] = nil
    return require("managers." .. module)
end

test("the script updates first, then hands over to termux-boot.sh", function()
    reset()
    local Boot = fresh("boot")
    local body = Boot.script("/repo")
    assert(body:find("REJOIN_DIR='/repo'", 1, true), "repo folder not baked in")
    assert(body:find("update.sh", 1, true))
    assert(body:find("no-auto-update", 1, true), "auto-update opt-out missing")
    assert(body:find("termux-boot.sh", 1, true))
    assert(body:find("Generated by rejoin install.sh", 1, true), "install marker missing")
    assert(body:match("^#!.*sh\n"), "shebang missing")
    -- update must come before the handover
    assert(body:find('sh "$REJOIN_DIR/update.sh"', 1, true) < body:find('exec sh "$REJOIN_DIR/termux-boot.sh"', 1, true))
end)

test("install writes the script, creates the folder and makes it executable", function()
    reset()
    local Boot = fresh("boot")
    local ok, path = Boot.install()
    assert(ok, tostring(path))
    assert(path == SCRIPT and files[SCRIPT], "script not written")
    assert(table.concat(execs, "\n"):find("mkdir -p '/home/tester/.termux/boot'", 1, true), "folder not created")
    assert(table.concat(execs, "\n"):find("chmod +x '" .. SCRIPT .. "'", 1, true), "not chmodded")
    assert(Boot.installed())
end)

test("install refuses without termux-boot.sh", function()
    reset()
    files["/repo/termux-boot.sh"] = nil
    local Boot = fresh("boot")
    local ok, err = Boot.install()
    assert(not ok and err:find("termux-boot.sh", 1, true))
    assert(not files[SCRIPT], "half-written script")
end)

test("uninstall only removes the boot script", function()
    reset()
    files[SCRIPT] = "x"
    local Boot = fresh("boot")
    local ok = Boot.uninstall()
    assert(ok and not files[SCRIPT])
    assert(files["/repo/termux-boot.sh"], "termux-boot.sh must stay")
    local okAgain, err = Boot.uninstall()
    assert(not okAgain and err:find("belum terpasang", 1, true))
end)

test("the boot log is never pasted into the engine log or read when absent", function()
    reset()
    local Boot = fresh("boot")
    local out, err = Boot.tailLog(10)
    assert(out == nil and err == "no_log")
    files["/repo/data/boot.log"] = "line\n"
    local tail = Boot.tailLog(10)
    assert(tail == "line\n")
    assert(table.concat(execs, "\n"):find("tail -n 10 '/repo/data/boot.log'", 1, true))
end)

test("status reports the app, script and log state", function()
    reset()
    files[SCRIPT] = "x"
    local Boot = fresh("boot")
    local st = Boot.status()
    assert(st.installed and st.logExists == false)
    assert(st.path == SCRIPT and st.log == "/repo/data/boot.log")
end)

test("uninstall lists boot, heartbeat, config and data, and says the repo stays", function()
    reset()
    files[SCRIPT] = "x"
    files["/sdcard/Delta/Autoexecute/rejoin_heartbeat.lua"] = "-- REJOIN_HEARTBEAT\n"
    files["/repo/config/config.lua"] = "cfg"
    files["/repo/data"] = "d"
    local Uninstall = fresh("uninstall")
    local targets = Uninstall.targets()
    local joined = {}
    for _, t in ipairs(targets) do joined[#joined + 1] = t.what end
    local text = table.concat(joined, "\n")
    assert(text:find("auto%-boot"))
    assert(text:find("heartbeat"))
    assert(text:find("config"))
    assert(text:find("TIDAK dihapus"), "repo must be announced as kept")
    assert(Uninstall.removable())
end)

test("uninstall runAll removes its targets but keeps the repo and termux-boot.sh", function()
    reset()
    files[SCRIPT] = "x"
    files["/sdcard/Delta/Autoexecute/rejoin_heartbeat.lua"] = "-- REJOIN_HEARTBEAT\n"
    files["/repo/config/config.lua"] = "cfg"
    files["/repo/data"] = "d"
    local Uninstall = fresh("uninstall")
    local results = Uninstall.runAll()
    local text = table.concat(results, "\n")
    assert(not files[SCRIPT], "boot script kept")
    assert(not files["/sdcard/Workspace/rejoin/rejoin_heartbeat.lua"], "heartbeat kept")
    assert(text:find("Dihapus: /repo/config", 1, true), "config not wiped")
    assert(text:find("Dihapus: /repo/data", 1, true), "data not wiped")
    assert(files["/repo/termux-boot.sh"], "termux-boot.sh deleted")
    assert(text:find("Folder repo tetap"), "kept repo not reported")
    -- other Autoexecute scripts are never touched
    assert(not table.concat(results, "\n"):find("Workspace/rejoin/other.lua"))
end)

test("a same-named heartbeat script rejoin did not write is left alone", function()
    reset()
    files["/sdcard/Delta/Autoexecute/rejoin_heartbeat.lua"] = "-- my own\n"
    local Uninstall = fresh("uninstall")
    local targets = Uninstall.targets()
    local text = {}
    for _, t in ipairs(targets) do text[#text + 1] = t.what end
    assert(not table.concat(text, "\n"):find("heartbeat"))
    Uninstall.runAll()
    assert(files["/sdcard/Delta/Autoexecute/rejoin_heartbeat.lua"] == "-- my own\n")
end)

test("every found executor loses its copy, not just the configured one", function()
    reset()
    files["/sdcard/Delta/Autoexecute/rejoin_heartbeat.lua"] = "-- REJOIN_HEARTBEAT\n"
    files["/sdcard/Other/Autoexecute/rejoin_heartbeat.lua"] = "-- REJOIN_HEARTBEAT\n"
    package.loaded["managers.executor"] = { found = { { path = "/sdcard/Other/Autoexecute" } } }
    local Uninstall = fresh("uninstall")
    Uninstall.runAll()
    assert(not files["/sdcard/Delta/Autoexecute/rejoin_heartbeat.lua"])
    assert(not files["/sdcard/Other/Autoexecute/rejoin_heartbeat.lua"])
    package.loaded["managers.executor"] = nil
end)

test("nothing to remove is reported honestly", function()
    reset()
    local Uninstall = fresh("uninstall")
    assert(not Uninstall.removable())
    local results = Uninstall.runAll()
    assert(table.concat(results, "\n"):find("belum terpasang"))
end)

os.getenv, os.execute, os.remove = realGetenv, realExecute, realRemove

print(string.format("%d passed, %d failed", passed, failed))
os.exit(failed == 0 and 0 or 1)
